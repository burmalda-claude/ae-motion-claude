"""Motion lexicon (/lexicon): 144 motion names (motion-prompt, MIT) + the ae-motion layer (Russian, kit mapping, energy, modes).

  python lexicon.py                 validate, write references/lexicon.md (+ docs/lexicon.json when the repo's docs/ exists)
  python lexicon.py --check         validate and fail if the generated files are stale
  python lexicon.py find <words>    search names / meanings / tags / kit (ru, en, ja), best 8 with the kit mapping
  python lexicon.py show 043        one entry in full: spec, kit, how to ask

Sources: lexicon/motion-prompt/<pack>.json (upstream meta, untouched) and lexicon/ae.json (ours, see its _doc).
Validation: every upstream id has an ae entry and back, every kit name is a real kit export or CutKind, every mode exists.
"""
import json, re, sys
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
LEX = SKILL / "lexicon"
DOCS = SKILL.parents[3] / "docs"  # repo root docs/ (GitHub Pages); absent in an installed plugin
SPEC_URL = "https://showheyohtaki.github.io/motion-prompt/api/v1/en/e/{id}.txt"


def kit_names():
    names = set()
    for f in (SKILL / "kit").glob("*.ts*"):
        names |= set(re.findall(r"^export (?:const|function) (\w+)", f.read_text(), re.M))
    cuts = (SKILL / "kit" / "cuts.tsx").read_text()
    kinds = set(re.findall(r'\|\s*"(\w+)"', cuts[cuts.index("export type CutKind"):cuts.index("export const CUT_CATEGORY")]))
    return names, kinds


def load():
    ae = json.loads((LEX / "ae.json").read_text())
    packs = sorted((json.loads(p.read_text()) for p in (LEX / "motion-prompt").glob("*.json")), key=lambda d: d["order"])
    items = []
    for p in packs:
        cats = {c["slug"]: c for c in p["categories"]}
        for i, e in enumerate(p["elements"]):
            id_ = f"{(p['order'] - 1) * 24 + i + 1:03d}"  # upstream numbering: 24 per pack, in pack order
            a = ae.get(id_) or sys.exit(f"ae.json: no entry for #{id_} {e['name']['en']}")
            items.append({
                "id": id_, "pack": p["pack"], "cell": i,
                "packName": {"en": p["title"]["en"], "ru": ae["_packs"][p["pack"]]},
                "cat": {"en": cats[e["category"]]["en"], "ru": ae["_cats"][f"{p['pack']}/{e['category']}"]},
                "name": {"en": e["name"]["en"], "ja": e["name"]["ja"], "ru": a["ru"]},
                "meaning": {"en": e["meaning"]["en"], "ru": a["m"]},
                "ask": {"en": e["ask"]["en"], "ru": a["ask"]},
                "summary": e["summary"]["en"], "spec": e["spec"]["en"], "use": e["use"]["en"],
                "tags": e["tags"], "kit": a["kit"], "e": a["e"], "modes": a["modes"],
            })
    extra = {k for k in ae if not k.startswith("_")} - {it["id"] for it in items}
    assert not extra, f"ae.json: ids with no upstream element: {sorted(extra)}"
    return items


def validate(items):
    names, kinds = kit_names()
    modes = {p.stem for p in (SKILL / "modes").glob("*.json")}
    errs = []
    for it in items:
        for k in it["kit"]:
            k = k.lstrip("~")
            ok = k[4:] in kinds if k.startswith("cut:") else k.split(":")[0] in names
            if not ok:
                errs.append(f"#{it['id']}: kit '{k}' is not a kit export / CutKind")
        errs += [f"#{it['id']}: unknown mode '{m}'" for m in it["modes"] if m not in modes]
        if it["e"] not in (1, 2, 3):
            errs.append(f"#{it['id']}: energy must be 1–3")
    assert len(items) == 144, f"expected 144 names, got {len(items)}"
    if errs:
        sys.exit("lexicon invalid:\n  " + "\n  ".join(errs))


def related(items, it, n=4):
    """Neighbours by shared tags, kit and category — what to try instead or next."""
    def score(o):
        return (len(set(it["tags"]) & set(o["tags"])) * 2 + len({k.lstrip("~") for k in it["kit"]} & {k.lstrip("~") for k in o["kit"]}) * 3
                + (o["cat"]["en"] == it["cat"]["en"] and o["pack"] == it["pack"]))
    ranked = sorted((o for o in items if o is not it), key=lambda o: (-score(o), o["id"]))
    return [o["id"] for o in ranked[:n] if score(o) > 0]


def kit_md(kit):
    if not kit:
        return "— spec"
    out = []
    for k in kit:
        approx, k = k.startswith("~"), k.lstrip("~")
        k = f'transition("{k[4:]}")' if k.startswith("cut:") else k.replace(":", " · ")
        out.append(("≈ " if approx else "") + f"`{k}`")
    return ", ".join(out)


def render_md(items):
    lines = [
        "# Motion lexicon: 144 names → kit",
        "",
        "Generated by `tools/lexicon.py` from `lexicon/` — do not edit by hand. Names: [motion-prompt](https://github.com/showheyohtaki/motion-prompt) (MIT, © Shohei Ohtaki). Visual gallery: `docs/` (GitHub Pages).",
        "",
        "**How to use.** When the user names a move (in any language, by number `#043`, or by description), find it here",
        "(`python tools/lexicon.py find <words>` is cheaper than reading this file) and build it with the listed kit pieces.",
        "`≈` = close look from the kit, not the exact move: say so. `— spec` = no kit piece: build it from the upstream spec",
        "(`python tools/lexicon.py show <id>`, or " + SPEC_URL.format(id="<id>") + " — a Canvas reference whose timings and easing to keep).",
        "In the brief, offer names from here instead of vague adjectives (\"whip pan, 8 f\" beats \"dynamic transition\").",
        "Energy: 1 calm · 2 medium · 3 hard.",
        "",
    ]
    pack = None
    for it in items:
        if it["pack"] != pack:
            pack = it["pack"]
            lines += ["", f"## {it['packName']['en']} / {it['packName']['ru']} (`{pack}`)", "", "| # | Name | Kit | E | Ask (ru) |", "|---|---|---|---|---|"]
        lines.append(f"| {it['id']} | **{it['name']['en']}** / {it['name']['ru']} — {it['meaning']['en']} | {kit_md(it['kit'])} | {it['e']} | {it['ask']['ru']} |")
    return "\n".join(lines) + "\n"


def site_json(items):
    for it in items:
        it["related"] = related(items, it)
    return json.dumps(items, ensure_ascii=False, separators=(",", ":"))


def outputs(items):
    out = {SKILL / "references" / "lexicon.md": render_md(items)}
    if DOCS.is_dir():
        out[DOCS / "lexicon.json"] = site_json(items)
    return out


def find(items, query):
    # shortcut: crude stem (drop 2 end letters of long words) so "тряска" finds "тряской"; a real stemmer if search gets noisy
    words = [w[:-2] if len(w) >= 6 else w for w in query.lower().split()]
    def score(it):
        hay = " ".join([*it["name"].values(), *it["meaning"].values(), " ".join(it["tags"]), " ".join(it["kit"]), it["cat"]["en"], it["cat"]["ru"]]).lower()
        names = " ".join(it["name"].values()).lower()
        at = lambda w, s: re.search(r"(?<!\w)" + re.escape(w), s)  # word-prefix match: "свип" is not a hit for "вип"
        return sum((3 if at(w, names) else 1) for w in words if at(w, hay) or w.lstrip("#") == it["id"])
    ranked = sorted(((score(it), it) for it in items), key=lambda x: (-x[0], x[1]["id"]))
    best = ranked[0][0]
    hits = [it for s, it in ranked if s and s * 2 >= best][:8]  # drop weak partial matches ("пан" in "панель")
    for it in hits:
        print(f"#{it['id']} {it['name']['en']} / {it['name']['ru']} — {it['meaning']['ru']}\n     kit: {kit_md(it['kit'])} · E{it['e']} · ask: {it['ask']['ru']}")
    return hits


def show(items, id_):
    it = next((it for it in items if it["id"] == id_.lstrip("#").zfill(3)), None) or sys.exit(f"no #{id_}")
    print(f"#{it['id']} {it['name']['en']} ({it['name']['ja']}) / {it['name']['ru']} · {it['packName']['en']} · {it['cat']['en']}")
    print(f"meaning: {it['meaning']['en']} / {it['meaning']['ru']}\nsample: {it['summary']}\nspec:")
    print("\n".join(f"  - {s}" for s in it["spec"]))
    print(f"use: {it['use']}\nkit: {kit_md(it['kit'])} · energy {it['e']} · modes: {', '.join(it['modes']) or '—'}")
    print(f"ask: {it['ask']['ru']} | {it['ask']['en']}\nreference code: {SPEC_URL.format(id=it['id'])}")
    print(f"related: {', '.join('#' + r for r in related(items, it))}")


if __name__ == "__main__":
    items = load()
    validate(items)
    if len(sys.argv) > 2 and sys.argv[1] == "find":
        find(items, " ".join(sys.argv[2:])) or print("nothing found — try English or a tag (whip, zoom, glitch, mask…)")
    elif len(sys.argv) > 2 and sys.argv[1] == "show":
        show(items, sys.argv[2])
    elif "--check" in sys.argv:
        stale = [str(p) for p, text in outputs(items).items() if not p.exists() or p.read_text() != text]
        sys.exit(f"stale, run tools/lexicon.py: {stale}" if stale else print("lexicon ok: 144 names, outputs fresh"))
    else:
        for p, text in outputs(items).items():
            p.write_text(text)
            print("wrote", p)
